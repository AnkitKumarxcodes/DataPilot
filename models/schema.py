from pydantic import BaseModel, Field
from typing import Annotated , Literal
from operator import add

class AgentState(BaseModel):
    """
    Represents the state of an agent in the system.
    """
    message: Annotated[list, add] =  Field(... , description="The current message or status of the agent.")
    user_input: Annotated[str, add] = Field(... , description="The input provided by the user to the agent.")
    curated_ques: str = Field(... , description="A list of curated user questions associated with the agent.")
    prompt_query_context: str = Field(... , description="A detailed prompt with SQL DB context that will help agent to generate a better response.")
    is_safe : Literal["Yes", "No"] = Field(... , description="Indicates whether the agent's response is safe or not.")
    generated_Sql_query: str = Field(... , description="The SQL query generated by the agent based on the user's input and context.")
    sql_query_execution_result: str = Field(... , description="The result of executing the generated SQL query against the database.")
    final_ans: str = Field(... , description="The final answer or response generated by the agent after processing the user's input and context.")